INSERT INTO app.calendar_days(day,working,source,revision)
SELECT d::date,
 extract(isodow FROM d)<6 AND NOT EXISTS(SELECT 1 FROM holidays h WHERE h.day=d::date),
 coalesce((SELECT h.source FROM holidays h WHERE h.day=d::date),CASE WHEN extract(year FROM d)=2026 THEN 'ПК РФ 2026' ELSE 'ТК РФ ст.112, 2027 (переносы января — сверить)' END),
 1
FROM generate_series('2026-01-01'::date,'2027-12-31'::date,'1 day') d
ON CONFLICT(day) DO NOTHING;
