-- 2026: постановление Правительства РФ о переносе выходных в 2026 году — 3 января → 9 января, 4 января → 31 декабря.
--   Нерабочие: 1–11 января, 23 февраля, 9 марта (8 марта — воскресенье), 1 мая, 11 мая (9 мая — суббота), 12 июня, 4 ноября, 31 декабря.
-- 2027: праздники по ст. 112 ТК РФ с автоматическим переносом совпавших с выходными (1 мая → 3 мая, 9 мая → 10 мая, 12 июня → 14 июня).
--   Перенос выходных 2 и 3 января 2027 устанавливается отдельным постановлением — сверить и при необходимости поправить
--   через POST /api/v1/admin/calendar (PROCESS_ADMIN); существующие записи этой миграцией не перезаписываются.
